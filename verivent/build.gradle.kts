// The viewer page lives as real html/css/js under web/ (editable, lintable); this task inlines
// them into a single Kotlin raw-string constant so the served page stays self-contained.
val generateWebPage = tasks.register("generateWebPage") {
    val webDir = layout.projectDirectory.dir("web")
    val outputDir = layout.buildDirectory.dir("generated/webpage/kotlin")
    inputs.dir(webDir).withPathSensitivity(PathSensitivity.RELATIVE)
    outputs.dir(outputDir)
    doLast {
        val page = webDir.file("index.html").asFile.readText()
            .replace("@VERIVENT_CSS@", webDir.file("styles.css").asFile.readText().trimEnd('\n'))
            .replace("@VERIVENT_JS@", webDir.file("app.js").asFile.readText().trimEnd('\n'))
        val escaped = page.replace("$", "\${'$'}")
        check("\"\"\"" !in escaped) { "web page must not contain triple quotes" }
        val out = outputDir.get().file("io/github/asanre/verivent/web/WebPage.kt").asFile
        out.parentFile.mkdirs()
        out.writeText(
            "package io.github.asanre.verivent.web\n\n" +
                "// Generated by :verivent:generateWebPage from web/. Do not edit.\n" +
                "internal val INDEX_HTML: String = \"\"\"\n" + escaped + "\"\"\"\n",
        )
    }
}

// The library's own version, for the source an export names; Kotlin Multiplatform has no BuildConfig.
val generateVersion = tasks.register("generateVersion") {
    val versionName = providers.gradleProperty("VERSION_NAME")
    val outputDir = layout.buildDirectory.dir("generated/version/kotlin")
    inputs.property("versionName", versionName)
    outputs.dir(outputDir)
    doLast {
        val out = outputDir.get().file("io/github/asanre/verivent/web/VeriventVersion.kt").asFile
        out.parentFile.mkdirs()
        out.writeText(
            "package io.github.asanre.verivent.web\n\n" +
                "// Generated by :verivent:generateVersion from VERSION_NAME. Do not edit.\n" +
                "internal const val VERIVENT_VERSION: String = \"${versionName.get()}\"\n",
        )
    }
}

kotlin {
    // Binary API dump of each published module, checked against the committed one in `check`, so
    // a release that only adds can't silently remove or change a public signature.
    @OptIn(org.jetbrains.kotlin.gradle.dsl.abi.ExperimentalAbiValidation::class)
    abiValidation {
        enabled.set(true)
    }
    compilerOptions {
        optIn.add("kotlin.time.ExperimentalTime")
        optIn.add("kotlin.concurrent.atomics.ExperimentalAtomicApi")
    }
    androidTarget {
        compilerOptions {
            jvmTarget.set(JvmTarget.JVM_11)
        }
    }
    iosArm64()
    iosSimulatorArm64()
    // Only for the npm package of the validator (see npm/): the browser checks events with the same
    // rules and messages as the device. Apps on Kotlin/JS aren't a supported target.
    js {
        outputModuleName = "verivent"
        nodejs()
        // ES modules export each declaration at the top level (`import { Plan } from "verivent"`),
        // where CommonJS would nest them under the Kotlin package.
        useEsModules()
        binaries.library()
        generateTypeScriptDefinitions()
        compilations["main"].packageJson {
            version = providers.gradleProperty("VERSION_NAME").get()
        }
    }

    // The web viewer's server runs on the devices only: `mobile` sits between common and the
    // Android and iOS source sets, so the JS build never sees Ktor.
    applyDefaultHierarchyTemplate()

    sourceSets {
        commonMain.get().kotlin.srcDir(generateVersion)
        commonMain.dependencies {
            api(libs.kotlinx.coroutines.core)
            // BodyCapture's content types and charsets; it used to arrive through the server.
            implementation(libs.ktor.http)
            implementation(libs.kotlinx.serialization.json)
        }
        commonTest.dependencies {
            implementation(kotlin("test"))
            implementation(libs.kotlinx.coroutines.test)
        }
        val mobileMain by creating {
            dependsOn(commonMain.get())
            kotlin.srcDir(generateWebPage)
            dependencies {
                implementation(libs.ktor.server.core)
                implementation(libs.ktor.server.cio)
                implementation(libs.ktor.server.sse)
            }
        }
        val mobileTest by creating {
            dependsOn(commonTest.get())
            dependencies {
                implementation(libs.ktor.server.test.host)
                implementation(libs.ktor.client.cio)
            }
        }
        androidMain.get().dependsOn(mobileMain)
        iosMain.get().dependsOn(mobileMain)
        androidUnitTest.get().dependsOn(mobileTest)
        iosTest.get().dependsOn(mobileTest)
    }
}

